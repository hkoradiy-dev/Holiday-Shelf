"""
Holiday Shelf — Streamlit app
Run: streamlit run app.py
Expects data/product_summary.csv, data/weekly.csv, data/promo_check.csv
(generated by pipeline.py) to already exist.
"""

import streamlit as st
import pandas as pd
import plotly.express as px
from pathlib import Path

DATA_DIR = Path(__file__).parent / "data"

st.set_page_config(page_title="Holiday Shelf", layout="wide")


@st.cache_data
def load_product_summary():
    return pd.read_csv(DATA_DIR / "product_summary.csv")


@st.cache_data
def load_weekly():
    return pd.read_csv(DATA_DIR / "weekly.csv", parse_dates=["week_start"])


@st.cache_data
def load_promo_check():
    return pd.read_csv(DATA_DIR / "promo_check.csv")


if "shortlist" not in st.session_state:
    st.session_state.shortlist = {}  # item_name -> row dict


@st.cache_data
def load_pairs():
    return pd.read_csv(DATA_DIR / "bundle_pairs.csv")


@st.cache_data
def load_rescue():
    return pd.read_csv(DATA_DIR / "cart_rescue.csv")


@st.cache_data
def load_order_stats():
    """Orders analysed, average products per order, orders with 2+ products."""
    o = pd.read_csv(DATA_DIR / "orders_v2.csv", usecols=["transaction_id"])
    per_order = o.groupby("transaction_id").size()
    return len(per_order), float(per_order.mean()), int((per_order >= 2).sum())


def add_to_shortlist(row: dict, key: str | None = None):
    st.session_state.shortlist[key or row["item_name"]] = row


def remove_from_shortlist(item_name: str):
    st.session_state.shortlist.pop(item_name, None)


st.sidebar.title("Holiday Shelf")
page = st.sidebar.radio(
    "Go to",
    ["Shelf Scorecard", "Opportunity Finder", "Bundles & Cart Rescue", "Promo Check", "Season Playbook", "Shortlist Builder"],
)

st.sidebar.markdown("---")
st.sidebar.markdown(f"**Shortlist: {len(st.session_state.shortlist)} products**")
if st.session_state.shortlist:
    with st.sidebar.expander("View shortlist"):
        for name in list(st.session_state.shortlist.keys()):
            c1, c2 = st.columns([4, 1])
            c1.caption(name)
            if c2.button("✕", key=f"remove_{name}"):
                remove_from_shortlist(name)
                st.rerun()

LABEL_COLORS = {
    "Star": "#2ecc71",
    "Hidden Gem": "#9b59b6",
    "Window-Shopper": "#e67e22",
    "Low Priority": "#95a5a6",
    "Not Enough Data": "#bdc3c7",
}

